"""Focused local tests for the public-source commit and release guard."""

import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parent))
from audit_public import audit_tree, inspect_blob


class PublicAuditTests(unittest.TestCase):
    def test_original_source_allowed(self):
        self.assertEqual(inspect_blob("tools/helper.py", b"print('local tool')\n"), [])

    def test_private_paths_and_renamed_binary(self):
        self.assertTrue(inspect_blob("original/game/EBOOT.BIN", b"x"))
        self.assertTrue(inspect_blob("generated/ppu/ppu_recomp_000.cpp", b"x"))
        self.assertTrue(inspect_blob("innocent.txt", b"\x7fELF\x02\x02"))
        self.assertTrue(inspect_blob("innocent.txt", b"MZ" + b"\0" * 100))

    def test_lifted_source_after_rename(self):
        self.assertTrue(inspect_blob("source.cpp", b"/* Auto-generated by spu_lifter.py */\n"))
        self.assertTrue(inspect_blob("source.txt", b"/* Auto-generated by spu_lifter.py */\n"))
        self.assertTrue(inspect_blob("source.c", b"void mspr_wws_pm_spu_func_00000A00(spu_context* ctx) {\n}"))

    def test_release_tree_blocks_private_directory_and_symlink(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            (root / "README.md").write_text("Independent source\n")
            (root / "generated").mkdir()
            (root / "generated" / "hidden.cpp").write_text("x")
            names = [name for name, _ in audit_tree(root)]
            self.assertIn("generated/", names)
            if hasattr(os, "symlink"):
                try:
                    os.symlink(root / "README.md", root / "link.txt")
                except OSError:
                    pass
                else:
                    self.assertIn("link.txt", [name for name, _ in audit_tree(root)])

    def test_private_reports_only_when_enabled(self):
        report = "generated/analysis/t138/REPORT.md"
        text = b"# Report\nFrame time 193-243 ms; guest function 0x0072E1E0.\n"
        self.assertTrue(inspect_blob(report, text))
        self.assertEqual(inspect_blob(report, text, private_reports=True), [])
        self.assertEqual(inspect_blob("generated/analysis/t138/tools/x.py", b"print(1)\n",
                                      private_reports=True), [])
        # Everything else under generated/ stays private.
        for name in ("generated/ppu/ppu_recomp_000.cpp", "generated/analysis/EBOOT.functions.json",
                     "generated/analysis/t138/logs/run.md", "generated/analysis/t138/data.json"):
            self.assertIn("private/generated directory",
                          inspect_blob(name, b"x", private_reports=True), name)

    def test_private_report_content_rules(self):
        report = "generated/analysis/t138/REPORT.md"
        cases = {
            b"  0072E1E0:  7c0802a6  mflr r0\n": "guest disassembly listing",
            b"| 00038790 | lqd $3, 0($1) |\n".replace(b"| ", b""): "guest disassembly listing",
            b"0x" + b", 0x".join([b"45"] * 300) + b"\n": "hex dump",
            b"see C:\\Users\\someone\\Desktop\\x\n": "local user path (personal data)",
        }
        for data, reason in cases.items():
            self.assertIn(reason, inspect_blob(report, data, private_reports=True), data[:40])
        self.assertTrue(inspect_blob(report, b"/* Auto-generated by spu_lifter.py */\n",
                                     private_reports=True))

    def test_launcher_icons_exempt_only_exactly(self):
        ico = b"\x00\x00\x01\x00" + b"\x00\xff" * 64
        png = b"\x89PNG\r\n\x1a\n" + b"\x00\xff" * 64
        self.assertEqual(inspect_blob("launcher/electron/assets/icon.ico", ico), [])
        self.assertEqual(inspect_blob("launcher/electron/assets/icon.png", png), [])
        # another name, another folder, the wrong header, an oversized file or an executable stay blocked
        self.assertTrue(inspect_blob("launcher/electron/assets/other.png", png))
        self.assertTrue(inspect_blob("launcher/electron/ui/icon.png", png))
        self.assertTrue(inspect_blob("launcher/electron/assets/icon.png", ico))
        self.assertTrue(inspect_blob("launcher/electron/assets/icon.png", png + b"\x00" * (512 * 1024)))
        self.assertTrue(inspect_blob("launcher/electron/assets/icon.ico", b"MZ" + b"\x00" * 64))

    def test_private_reports_refused_for_release_tree(self):
        script = Path(__file__).resolve().parent / "audit_public.py"
        with tempfile.TemporaryDirectory() as temp:
            result = subprocess.run([sys.executable, str(script), "--tree", temp, "--private-reports"],
                                    capture_output=True, text=True)
            self.assertEqual(result.returncode, 2, result.stdout + result.stderr)

    def test_staged_audit_checks_blob_not_worktree(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            script = Path(__file__).resolve().parent / "audit_public.py"
            subprocess.run(["git", "init", "-q", str(root)], check=True)
            candidate = root / "candidate.cpp"
            candidate.write_text("/* Auto-generated by ppu_lifter.py */\n")
            subprocess.run(["git", "-C", str(root), "add", "candidate.cpp"], check=True)
            candidate.write_text("Independent source now in worktree\n")
            result = subprocess.run([sys.executable, str(script), "--staged"],
                                    cwd=root, capture_output=True, text=True)
            self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
            self.assertIn("statically recompiled code signature", result.stdout)


if __name__ == "__main__":
    unittest.main()
