#!/usr/bin/env python3
"""Fail closed on private inputs and lifted output in a public commit/release.

This is a local-only guard, not a proof of copyright ownership. Inspect either
Git's staged blobs (not the worktree) or the exact source release staging tree.
"""

import argparse
import hashlib
import os
from pathlib import Path, PurePosixPath
import re
import subprocess
import sys


PRIVATE_DIRS = {
    "original", "private", "firmware", "generated", "build", "release",
    "dist", "out", "game", "mods", "recompiled", "generated_spu",
    "spu_lifted", "fw_spu", "__pycache__", ".git",
}
PRIVATE_NAMES = {"eboot.bin", "eboot.elf", "param.sfo", "libsre.sprx"}
PRIVATE_SUFFIXES = {
    ".iso", ".sfo", ".self", ".elf", ".prx", ".sprx", ".psarc",
    ".pkg", ".rap", ".rif", ".keys", ".klic", ".bin", ".o",
    ".obj", ".a", ".lib", ".dll", ".exe", ".pdb", ".ilk",
    ".exp", ".so", ".dylib", ".dmg", ".zip", ".7z", ".rar",
    ".png", ".jpg", ".jpeg", ".dds", ".wav", ".mp3", ".ogg",
    ".at3", ".bik", ".usm", ".ps3", ".dat", ".pack", ".pak",
}
# Renaming a known input must not bypass the path and signature rules.
KNOWN_PRIVATE_SHA256 = {
    "4f05f3227199bc65cf4f28cc82ef2749bfe978685c75b576a112e426a9145872",  # ISO
    "218cd8aa99355583026f203fcbbda03e17f6900118a942f7f086b556ea4994af",  # retail SELF
    "bbb7fe2545e54847483439f59cda54e907db23a111d7afe9a1b655624886b287",  # decrypted ELF
    "5c76379cbc13c5cf305120640bf0367cce8ebedcd31af61d8c46e73f5df397ec",  # PSARC
}
LIFTED_MARKER = re.compile(rb"(?m)^/\* Auto-generated by (?:ppu_lifter|spu_lifter|gen_hle_nids)\.py\b")
LIFTED_FUNCTION = re.compile(rb"(?m)^void\s+(?:mspr_\w+_)?spu_func_[0-9A-Fa-f]{8}\s*\(\s*spu_context\s*\*[^)]*\)\s*\{")
MAX_SOURCE_BYTES = 4 * 1024 * 1024

# --private-reports (the private project repository only, never a release):
# per-task reports generated/analysis/<task>/<name>.md and analysis scripts
# generated/analysis/<task>/tools/<name>.py may be committed after review, if
# they also carry no guest disassembly, long hex dumps or local user paths.
PRIVATE_REPORT = re.compile(r"^generated/analysis/[A-Za-z0-9_.-]+/(?:[^/]+\.md|tools/[^/]+\.py)$")
MAX_REPORT_BYTES = 1024 * 1024
GUEST_DISASSEMBLY = re.compile(
    rb"(?mi)^[\s|>*`-]*(?:0x)?[0-9a-f]{5,8}:?\s+(?:[0-9a-f]{8}\s+)?"
    rb"(?:lwz|lwzx|stw|stwu|stwx|lbz|stb|lhz|sth|ld|std|mflr|mtlr|mtctr|addi|addis|lis|ori|oris|"
    rb"rlwinm|cmpwi|cmplwi|bl|bctrl|blr|lqd|stqd|lqa|stqa|shufb|il|ila|ilhu|iohl|brsl|bi|selb|rotqby)\b")
HEX_DUMP = re.compile(rb"(?:[0-9A-Fa-f]{2}[ ,]?){512}|(?:0x[0-9A-Fa-f]{2},\s*){256}")
LOCAL_USER_PATH = re.compile(rb"(?i)[A-Z]:[\\/]+Users[\\/]+[^\\/\s\"']+")

# The launcher's own window/exe icons (project artwork drawn from icon.svg, not game data). Only these exact paths,
# only with the matching image header and under the size cap, skip the binary-file rules; the known-input hash,
# executable/archive signature and private-path rules still apply.
PROJECT_IMAGES = {
    "launcher/electron/assets/icon.ico": b"\x00\x00\x01\x00",
    "launcher/electron/assets/icon.png": b"\x89PNG\r\n\x1a\n",
}
MAX_PROJECT_IMAGE_BYTES = 512 * 1024
BINARY_RULES = {"private or binary file type", "binary content", "non-UTF-8 content requires manual review"}


def project_image(name: str, data: bytes) -> bool:
    magic = PROJECT_IMAGES.get(name)
    return magic is not None and data.startswith(magic) and len(data) <= MAX_PROJECT_IMAGE_BYTES


def inspect_private_report(name: str, data: bytes) -> list[str]:
    """Extra content rules for a generated/analysis report under --private-reports."""
    reasons = []
    if len(data) > MAX_REPORT_BYTES:
        reasons.append("report exceeds 1 MiB review limit")
    if GUEST_DISASSEMBLY.search(data):
        reasons.append("guest disassembly listing")
    if HEX_DUMP.search(data):
        reasons.append("hex dump")
    if LOCAL_USER_PATH.search(data):
        reasons.append("local user path (personal data)")
    return reasons


def inspect_blob(name: str, data: bytes, *, symlink: bool = False,
                 private_reports: bool = False) -> list[str]:
    """Return rejection reasons for one proposed public file."""
    normalized = name.replace("\\", "/")
    parts = PurePosixPath(normalized).parts
    reasons = []
    report = private_reports and bool(PRIVATE_REPORT.match(normalized))
    if not parts or normalized.startswith("/") or ".." in parts:
        reasons.append("unsafe path")
    if report:
        reasons.extend(inspect_private_report(normalized, data))
    elif any(part.lower() in PRIVATE_DIRS for part in parts[:-1]):
        reasons.append("private/generated directory")
    if parts and parts[-1].lower() in PRIVATE_NAMES:
        reasons.append("known proprietary filename")
    if parts and PurePosixPath(parts[-1]).suffix.lower() in PRIVATE_SUFFIXES:
        reasons.append("private or binary file type")
    if symlink:
        reasons.append("symbolic link requires manual review")
    if len(data) > MAX_SOURCE_BYTES:
        reasons.append("source file exceeds 4 MiB review limit")
    if hashlib.sha256(data).hexdigest() in KNOWN_PRIVATE_SHA256:
        reasons.append("known proprietary input hash")
    if data.startswith((b"\x7fELF", b"SCE\x00", b"\x00SCE", b"MZ", b"PSAR")):
        reasons.append("executable, SELF, or asset archive signature")
    if b"\x00" in data:
        reasons.append("binary content")
    # The lifter scripts contain these exact strings as output templates.
    if parts and PurePosixPath(parts[-1]).suffix.lower() != ".py" and (LIFTED_MARKER.search(data) or LIFTED_FUNCTION.search(data)):
        reasons.append("statically recompiled code signature")
    try:
        data.decode("utf-8")
    except UnicodeDecodeError:
        reasons.append("non-UTF-8 content requires manual review")
    if project_image(normalized, data):
        reasons = [r for r in reasons if r not in BINARY_RULES]
    return reasons


def audit_tree(root: Path) -> list[tuple[str, list[str]]]:
    if not root.is_dir():
        raise ValueError(f"Release staging tree does not exist: {root}")
    findings = []
    for current, dirs, files in os.walk(root, followlinks=False):
        # Keep private directories visible to the audit, but do not read all
        # their potentially multi-gigabyte contents.
        for directory in list(dirs):
            p = Path(current) / directory
            rel = p.relative_to(root).as_posix()
            if p.is_symlink():
                findings.append((rel, ["symbolic link requires manual review"]))
                dirs.remove(directory)
            elif directory.lower() in PRIVATE_DIRS:
                findings.append((rel + "/", ["private/generated directory in release"]))
                dirs.remove(directory)
        for filename in files:
            p = Path(current) / filename
            rel = p.relative_to(root).as_posix()
            if p.is_symlink():
                findings.append((rel, ["symbolic link requires manual review"]))
                continue
            if p.stat().st_size > MAX_SOURCE_BYTES:
                findings.append((rel, ["source file exceeds 4 MiB review limit"]))
                continue
            reasons = inspect_blob(rel, p.read_bytes())
            if reasons:
                findings.append((rel, reasons))
    return findings


def _git(*args: str) -> bytes:
    result = subprocess.run(["git", *args], stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE, check=False)
    if result.returncode:
        raise ValueError(result.stderr.decode("utf-8", "replace").strip())
    return result.stdout


def audit_staged(private_reports: bool = False) -> list[tuple[str, list[str]]]:
    findings = []
    for record in _git("ls-files", "--stage", "-z").split(b"\x00"):
        if not record:
            continue
        metadata, raw_path = record.split(b"\t", 1)
        mode, oid, stage = metadata.decode("ascii").split()
        if stage != "0":
            findings.append((os.fsdecode(raw_path), ["unmerged staged entry"]))
            continue
        name = os.fsdecode(raw_path)
        if mode == "160000":
            findings.append((name, ["submodule requires separate source/license audit"]))
            continue
        data = _git("cat-file", "blob", oid)
        reasons = inspect_blob(name, data, symlink=(mode == "120000"),
                               private_reports=private_reports)
        if reasons:
            findings.append((name, reasons))
    return findings


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--staged", action="store_true", help="audit the exact Git index")
    mode.add_argument("--tree", type=Path, help="audit an exact release staging directory")
    parser.add_argument("--private-reports", action="store_true",
                        help="with --staged: allow reviewed generated/analysis/<task>/*.md and "
                             "tools/*.py in the private project repository (never for releases)")
    args = parser.parse_args()
    if args.private_reports and not args.staged:
        parser.error("--private-reports applies to --staged only; release trees stay strict")
    try:
        findings = audit_staged(args.private_reports) if args.staged else audit_tree(args.tree)
    except ValueError as error:
        print(f"AUDIT ERROR: {error}", file=sys.stderr)
        return 2
    for name, reasons in findings:
        print(f"BLOCK {name}: {', '.join(reasons)}")
    if findings:
        print(f"Public-source audit failed: {len(findings)} item(s).")
        return 1
    print("Public-source audit passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
