// node check_includes.js <staged tree>: every #include "..." in the staged port and runtime sources resolves inside the
// bundle. A quoted include counts as resolved when the file is beside the including file or when some file in the
// bundle ends with that path (the build adds the include directories; CMake is not run here). Headers the build
// generates (the lift's ppu_recomp.h, the SPU lifts') are expected to be missing and listed apart.
'use strict';
const fs = require('fs');
const path = require('path');

const GENERATED = new Set(['ppu_recomp.h', 'spu_recomp.h', 'spu_recomp.c', 'ppu_hle_nids.h', 'sources.cmake']);
const SOURCE = /\.(c|cc|cpp|cxx|h|hh|hpp|hxx|inl)$/i;

function walk(dir, out = []) {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        const p = path.join(dir, e.name);
        if (e.isDirectory()) walk(p, out); else if (e.isFile()) out.push(p);
    }
    return out;
}

function check(root) {
    const files = walk(root);
    const rel = files.map(f => path.relative(root, f).split(path.sep).join('/'));
    const known = new Set(rel);
    const suffix = new Map();   // "a/b.h" -> true for every suffix of every file's path
    for (const r of rel) { const parts = r.split('/'); for (let i = 0; i < parts.length; i++) suffix.set(parts.slice(i).join('/'), true); }
    const unresolved = [], generated = [], notBuilt = [];
    let seen = 0;
    files.forEach((f, i) => {
        if (!SOURCE.test(f)) return;
        const text = fs.readFileSync(f, 'latin1');
        const re = /^\s*#\s*include\s*"([^"]+)"/gm;
        let m;
        while ((m = re.exec(text))) {
            seen++;
            const inc = m[1].replace(/\\/g, '/');
            const near = path.posix.normalize(path.posix.join(path.posix.dirname(rel[i]), inc));
            if (known.has(near) || suffix.has(path.posix.normalize(inc).replace(/^(\.\.\/)+/, ''))) continue;
            // test and bench sources are not part of the player build (PS3RECOMP_BUILD_TESTS is off): listed apart
            const inTests = /(^|\/)(tests?|bench)\//.test(rel[i]);
            (GENERATED.has(path.posix.basename(inc)) ? generated : inTests ? notBuilt : unresolved).push(`${rel[i]}: "${inc}"`);
        }
    });
    return { seen, unresolved, generated, notBuilt };
}

if (require.main === module) {
    const root = process.argv[2];
    if (!root) { console.error('usage: node check_includes.js <staged tree>'); process.exit(2); }
    const r = check(path.resolve(root));
    console.log(`include check: ${r.seen} quoted includes, ${r.unresolved.length} unresolved, ${r.generated.length} generated by the build`);
    for (const u of r.unresolved.slice(0, 80)) console.log('  UNRESOLVED ' + u);
    process.exit(r.unresolved.length ? 1 : 0);
}
module.exports = { check };
