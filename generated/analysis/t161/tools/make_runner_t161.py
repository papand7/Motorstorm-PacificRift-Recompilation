"""T161 fast race-benchmark runner (PROPOSED; needs authorisation before any build or launch).
Derives t161/ab/run_t161.py from t158/ab/run_t158ab.py. Same route, inputs, environment, caps
(200 s controller / 195+15 s host), race stop at entry + 90 s and per-launch fresh HDD copies.
Changes only the menu pacing: nav() is driven by nav_policy_t161.NavPolicy.
Arms:
  N = T158 C1 exe, T158 pacing (settle 6.5 s, no retry)      exe key 'b'   - pacing control
  F = T158 C1 exe, fast pacing (settle 1.5 s, 2 retries)     exe key 'b'
  H = F + PS3_HLE_WAIT_MS=1000 on an exe built from ps3recomp-t161 (not built) exe key 'h'
  py -3 generated/analysis/t161/tools/make_runner_t161.py
  py -3 generated/analysis/t161/ab/run_t161.py prepare b|h ; launch N|F|H <tag>"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
AB = HERE.parent / 'ab'
src = (HERE.parents[1] / 't158' / 'ab' / 'run_t158ab.py').read_text(encoding='utf-8')


def sub(old, new, count=1):
    global src
    assert src.count(old) == count, (old[:80], src.count(old))
    src = src.replace(old, new)


sub('"""T158 SPU codegen A/B (generated by t158/tools/make_runner_t158.py from t156/ab/run_t156ab.py; PROPOSED, needs authorisation):\n',
    '"""T161 fast race benchmark (generated by t161/tools/make_runner_t161.py from t158/ab/run_t158ab.py; PROPOSED, needs authorisation):\n')
sub("  py -3 run_t158ab.py prepare a|b ; launch A|B <tag>\n", "  py -3 run_t161.py prepare b|h ; launch N|F|H <tag>\n")
sub("from pathlib import Path\n", "from pathlib import Path\n"
    "sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'tools'))\n"
    "from nav_policy_t161 import NavPolicy\n")
sub("SRC_EXES = {'a': ROOT / 'build' / 'motorstorm-t156' / 'MotorStormPacificRiftRecomp.exe',\n"
    "            'b': ROOT / 'build' / 'motorstorm-t158-c1' / 'MotorStormPacificRiftRecomp.exe'}",
    "SRC_EXES = {'b': ROOT / 'build' / 'motorstorm-t158-c1' / 'MotorStormPacificRiftRecomp.exe',\n"
    "            'h': ROOT / 'build' / 'motorstorm-t161-h' / 'MotorStormPacificRiftRecomp.exe'}   # h: not built")
i0, i1 = src.index("ARMS = {"), src.index("RSXI_AT_S = 30.0")
src = src[:i0] + """ENV = {**COMMON, **PERF, **TRACE, **T150, **WSTAT, **AOT}   # = T158 arm B
ARMS = {
    'N': ('b', ENV),
    'F': ('b', ENV),
    'H': ('h', {**ENV, 'PS3_HLE_WAIT_MS': '1000',     # T161 HLE import wait accounting
                # V2: PT also prints every import call >= 2 ms; the critical-path window (host-thread
                # CPU samples, syscall/usleep spans) covers the race load instead of the race.
                'PS3_TRACE_FILE': str(HERE / 'cpath_sites_v2.cfg'),
                'PS3_CRITICAL_PATH_TRACE': '40:100:{rt}/cpath.txt'}),
}
NAV = {'N': dict(settle_s=6.5, retries=0), 'F': dict(settle_s=1.5, retries=2), 'H': dict(settle_s=1.5, retries=2)}
""" + src[i1:]
sub("RUN_NAME = 't158-ab'", "RUN_NAME = 't161-fast'")
sub("            raise SystemExit('usage: run_t158ab.py launch A|B <tag>')",
    "            raise SystemExit('usage: run_t161.py launch N|F|H <tag>')")
sub("        ARM, RUN_NAME = arm, f't158-ab-{tag}'", "        ARM, RUN_NAME = arm, f't161-fast-{arm}{tag}'")
# nav(): same guards and route signature; pacing from NavPolicy.
i0 = src.index("    def nav(self):\n")
i1 = src.index("    def mark(self, label):\n")
src = src[:i0] + """    def nav(self):
        if self.nav_pol is None:
            self.nav_pol = NavPolicy(max_presses=self.MAX_PRESSES, **NAV[ARM])
            self.note('nav_policy', **NAV[ARM])
        pol = self.nav_pol
        sig = self.route_sig()
        # Stop pressing at the load screen (the last intended screen), not only once the race
        # loader 0x8EA00 is entered: with a 1.5 s settle a press could otherwise land in the
        # 0.3-0.4 s between the two (T158 C0/C1 controller logs).
        in_loader = bool(self.count('0008EA00')) or self.npage('gui/loadscre') >= 1
        if not pol.due(self.now(), sig, self.npage('gui/mainmenu') >= 1, in_loader):
            return
        pol.pressed()
        self.nav_step = pol.presses
        self.press(f'cross {pol.presses}', CROSS, 20)
        changed = self.wait(pol.confirm_s, lambda: self.route_sig() != sig)
        r = pol.result(self.now(), self.route_sig(), changed)
        if r == 'ok':
            self.note('nav_ok', step=pol.step, sig=list(self.route_sig()))
        elif r == 'retry':
            self.note('nav_retry', step=pol.step + 1, press=pol.presses)
        else:
            self.nav_manual = True
            self.note('nav_manual', step=pol.step + 1, why=f'no route transition in {pol.confirm_s:.0f} s')

""" + src[i1:]
sub("        self.nav_step, self.nav_manual, self.nav_t, self.nav_sig = 0, False, None, None",
    "        self.nav_step, self.nav_manual, self.nav_t, self.nav_sig = 0, False, None, None\n"
    "        self.nav_pol = None")
assert 'self.SETTLE' not in src
AB.mkdir(exist_ok=True)
for name in ('cpath_sites.cfg', 'snapshot_manifest.json'):
    s = HERE.parents[1] / 't158' / 'ab' / name
    if s.exists():
        (AB / name).write_bytes(s.read_bytes())
(AB / 'run_t161.py').write_text(src, encoding='utf-8')
print('wrote', AB / 'run_t161.py')
