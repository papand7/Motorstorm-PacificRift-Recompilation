"""T162: in-game runner, derived from t161/ab/run_t161.py like performance_next's: same route, fast pacing, inputs,
caps (195 s game / 210 s host), race stop at entry + 150 s, fresh HDD copies per launch, the 12 CELLMARK frame dumps.
One exe (key 'g' = build/motorstorm-t162-gvf, from tools/build_t162.cmd). Arms, T161 arm C environment plus:
  D = RSX_VTX_STATS=1000 (counters only; timing not used)
  A = RSX_GPU_PROF=60
  B = A + RSX_GPU_VERTEX_FETCH=1
  py -3 generated/analysis/t162/tools/make_runner_t162.py
  py -3 generated/analysis/t162/ab/run_t162.py prepare g ; launch D|A|B <tag>"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
AB = HERE.parent / 'ab'
T161 = HERE.parents[1] / 't161'
src = (T161 / 'ab' / 'run_t161.py').read_text(encoding='utf-8')


def sub(old, new, count=1):
    global src
    assert src.count(old) == count, (old[:80], src.count(old))
    src = src.replace(old, new)


sub('"""T161 fast race benchmark (generated by t161/tools/make_runner_t161.py from t158/ab/run_t158ab.py; PROPOSED, needs authorisation):\n',
    '"""T162 GPU vertex fetch D/A/B (generated by t162/tools/make_runner_t162.py from t161/ab/run_t161.py):\n  py -3 run_t162.py prepare g ; launch D|A|B <tag>\n')
sub("sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'tools'))\n",
    "sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 't161' / 'tools'))   # nav_policy_t161\n")
i0, i1 = src.index("SRC_EXES = {"), src.index("EXE, EXE_SHA = None, None")
src = src[:i0] + "SRC_EXES = {'g': ROOT / 'build' / 'motorstorm-t162-gvf' / 'MotorStormPacificRiftRecomp.exe'}\n" + src[i1:]
i0, i1 = src.index("ARMS = {"), src.index("RACE_STOP = {")
src = src[:i0] + """PROF = {'RSX_GPU_PROF': '60'}
ARMS = {
    'D': ('g', {**ENV_LEAN, 'RSX_VTX_STATS': '1000'}),
    'A': ('g', {**ENV_LEAN, **PROF}),
    'B': ('g', {**ENV_LEAN, **PROF, 'RSX_GPU_VERTEX_FETCH': '1'}),
}
""" + src[i1:]
sub("RACE_STOP = {'C': 150.0, 'D': 150.0}", "RACE_STOP = {'D': 150.0, 'A': 150.0, 'B': 150.0}")
i0 = src.index("NAV = {")
i1 = src.index("\n", src.index("'C': dict(settle_s=1.5, retries=2), 'D': dict(settle_s=1.5, retries=2)}")) + 1
src = src[:i0] + "NAV = {k: dict(settle_s=1.5, retries=2) for k in 'DAB'}\n" + src[i1:]
sub("RUN_NAME = 't161-fast'", "RUN_NAME = 't162'")
sub("            raise SystemExit('usage: run_t161.py launch N|F|H|L|A|B|C|D <tag>')",
    "            raise SystemExit('usage: run_t162.py launch D|A|B <tag>')")
sub("        ARM, RUN_NAME = arm, f't161-fast-{arm}{tag}'", "        ARM, RUN_NAME = arm, f't162-{arm}{tag}'")
AB.mkdir(exist_ok=True)
for name in ('cpath_sites.cfg', 'cpath_sites_v2.cfg', 'snapshot_manifest.json'):
    s = T161 / 'ab' / name
    if s.exists():
        (AB / name).write_bytes(s.read_bytes())
(AB / 'run_t162.py').write_text(src, encoding='utf-8')
print('wrote', AB / 'run_t162.py')
