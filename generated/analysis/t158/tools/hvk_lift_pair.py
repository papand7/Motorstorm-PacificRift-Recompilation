"""T158: lift the four Havok task images twice for the function-level harness (private output).

C0 = the production lift (no lifter arguments), C1 = the same plus --chain-chunks. Both use the
code.bin / functions.json / base / image id the build pipeline (spu_program_pipeline.py) uses, with
the symbol prefixes c0_<img>_ / c1_<img>_ so both link into one binary. Writes per image:
  <out>/<img>/c0/spu_recomp.{c,h}, <out>/<img>/c1/..., <out>/<img>/table.c (entries, registration)
  py -3 hvk_lift_pair.py <ps3recomp tree> <gen_c0 dir> <out dir> [images] [arm0 args] [arm1 args]
The optional arm arguments replace the lifter flags of the two slots (default '' and
'--chain-chunks'), e.g. '--chain-chunks' '--chain-chunks --chain-hoist' to compare C1 with C2.
"""
import json
import subprocess
import sys
from pathlib import Path

TREE, GEN, OUT = (Path(a).resolve() for a in sys.argv[1:4])
sys.path.insert(0, str(TREE / 'tools'))
from find_spu_functions import detect_functions  # noqa: E402

IMAGES = [('solver', 'spu_45c1b7bf045ac567a973f2b5c1fc62c90cbddebd5a1292296e07fc969a775177', 341580667),
          ('collide', 'spu_d51c6cebd3c35dfadd1c9fddaaa61c6721bd7913112fc1cb24933c8705c2683f', 491898574),
          ('raycast', 'spu_266e45a8fd8d59f18fba05552cbaf9074e346188660a29f9fe5f62d9e15fef98', 308733018),
          ('anim', 'spu_83451471f1c85a7dea41d41c2d7936a04eb693d7269e25a24d405ad1a569a7cc', 406081863)]
only = sys.argv[4].split(',') if len(sys.argv) > 4 and sys.argv[4] else None
ARM0 = sys.argv[5].split() if len(sys.argv) > 5 else []
ARM1 = sys.argv[6].split() if len(sys.argv) > 6 else ['--chain-chunks']

for short, name, image_id in IMAGES:
    if only and short not in only:
        continue
    src = GEN / name
    blob = (src / 'image.elf').read_bytes()
    _, (_off, base, _size) = detect_functions(blob, verbose=False)
    d = OUT / short
    for arm, extra in (('c0', ARM0), ('c1', ARM1)):
        o = d / arm
        o.mkdir(parents=True, exist_ok=True)
        cmd = [sys.executable, str(TREE / 'tools' / 'spu_lifter.py'), str(src / 'code.bin'), '--base', str(base),
               '--functions', str(src / 'functions.json'), '--symbol-prefix', f'{arm}_{short}_',
               '--report', str(o / 'lift.json'), '--output', str(o), '--image-id', str(image_id)] + extra
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            sys.exit(f'{short} {arm}: lifter failed\n{r.stdout}\n{r.stderr}')
        for fn in ('spu_recomp.c', 'spu_recomp.h'):
            p = o / fn
            t = p.read_text(encoding='utf-8')
            t = t.replace('#include "../../runtime/spu/spu_context.h"', '#include "spu_context.h"')
            t = t.replace('#include "../../runtime/spu/spu_helpers.h"', '#include "spu_helpers.h"')
            p.write_text(t, encoding='utf-8')
    rep = json.loads((d / 'c0' / 'lift.json').read_text())
    rep1 = json.loads((d / 'c1' / 'lift.json').read_text())
    starts = sorted({s for s, _ in rep['functions']})
    assert starts == sorted({s for s, _ in rep1['functions']}), short + ': C0/C1 entry sets differ'
    calls = sorted(set(rep['call_targets']))
    lo, hi = min(s for s, _ in rep['functions']), max(e for _, e in rep['functions'])
    L = ['/* generated by hvk_lift_pair.py */', '#include "spu_context.h"', '#include "hvk_table.h"']
    for arm in ('c0', 'c1'):
        L.append(f'extern void {arm}_{short}_spu_recomp_register(void);')
        for a in calls:
            L.append(f'extern void {arm}_{short}_spu_func_{a:08X}(spu_context*);')
    L.append(f'static const uint32_t s_starts[] = {{{", ".join(hex(a) for a in starts)}}};')
    L.append('static const hvk_entry s_calls[] = {')
    for a in calls:
        L.append(f'    {{0x{a:X}u, c0_{short}_spu_func_{a:08X}, c1_{short}_spu_func_{a:08X}}},')
    L.append('};')
    L.append(f'const hvk_image hvk_img = {{"{short}", "{(src / "image.elf").as_posix()}", {image_id}, '
             f'0x{lo:X}u, 0x{hi:X}u, s_starts, {len(starts)}u, s_calls, {len(calls)}u, '
             f'c0_{short}_spu_recomp_register, c1_{short}_spu_recomp_register}};')
    (d / 'table.c').write_text('\n'.join(L) + '\n', encoding='utf-8')
    print(short, 'base', hex(base), 'functions', len(starts), 'call targets', len(calls), 'code', hex(lo), hex(hi))
