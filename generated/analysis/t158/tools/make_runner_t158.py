"""T158 SPU code-generation game A/B runner (PROPOSED; needs authorisation before any launch).
Derives t158/ab/run_t158ab.py from t156/ab/run_t156ab.py: same route, intro skip, controller, race
entry, stop at race entry + 90 s, the T156 arm S environment (= T154 arm BA: T153 COMMON + PERF +
T150 + Wws stats + Wws AOT, critical-path window host s 150..172). The T156 worker pool stays off.
Arms differ only in the exe:
  A = build/motorstorm-t156     (ps3recomp 756c1e1, standard SPU lift)          exe key 'a'
  B = build/motorstorm-t158-c1  (ps3recomp 756c1e1, --chain-chunks for the four Havok images) key 'b'
  py -3 generated/analysis/t158/tools/make_runner_t158.py
  py -3 generated/analysis/t158/ab/run_t158ab.py prepare a|b   (copy + pin)  |  launch A|B <tag>"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
AB = HERE.parent / 'ab'
src = (HERE.parents[1] / 't156' / 'ab' / 'run_t156ab.py').read_text(encoding='utf-8')


def sub(old, new, count=1):
    global src
    assert src.count(old) == count, (old[:80], src.count(old))
    src = src.replace(old, new)


sub('"""T156 Havok worker-pool A/B (generated by t156/tools/make_runner_t156.py from t154/ab/run_t154ab.py; PROPOSED, needs authorisation):\n',
    '"""T158 SPU codegen A/B (generated by t158/tools/make_runner_t158.py from t156/ab/run_t156ab.py; PROPOSED, needs authorisation):\n')
sub("  py -3 run_t156ab.py launch S|P|D <tag>\n", "  py -3 run_t158ab.py prepare a|b ; launch A|B <tag>\n")
sub("SRC_EXES = {'w': ROOT / 'build' / 'motorstorm-t156' / 'MotorStormPacificRiftRecomp.exe'}",
    "SRC_EXES = {'a': ROOT / 'build' / 'motorstorm-t156' / 'MotorStormPacificRiftRecomp.exe',\n"
    "            'b': ROOT / 'build' / 'motorstorm-t158-c1' / 'MotorStormPacificRiftRecomp.exe'}")
i0, i1 = src.index("POOL = {'PS3_SPU_TASK_POOL': '1'}"), src.index("RSXI_AT_S = 30.0")
src = src[:i0] + """ARMS = {
    'A': ('a', {**COMMON, **PERF, **TRACE, **T150, **WSTAT, **AOT}),   # = T156 arm S (pool off), standard SPU lift
    'B': ('b', {**COMMON, **PERF, **TRACE, **T150, **WSTAT, **AOT}),   # same environment, --chain-chunks Havok lift
}
""" + src[i1:]
sub("RUN_NAME = 't156-ab'", "RUN_NAME = 't158-ab'")
sub("            raise SystemExit('usage: run_t156ab.py launch S|P|D <tag>')",
    "            raise SystemExit('usage: run_t158ab.py launch A|B <tag>')")
sub("        ARM, RUN_NAME = arm, f't156-ab-{tag}'", "        ARM, RUN_NAME = arm, f't158-ab-{tag}'")
assert 'PS3_SPU_TASK_POOL' not in src.split('ARMS = {')[1].split('}')[0]
AB.mkdir(exist_ok=True)
for name in ('cpath_sites.cfg', 'snapshot_manifest.json'):
    s = HERE.parents[1] / 't156' / 'ab' / name
    if s.exists():
        (AB / name).write_bytes(s.read_bytes())
(AB / 'run_t158ab.py').write_text(src, encoding='utf-8')
print('wrote', AB / 'run_t158ab.py')
