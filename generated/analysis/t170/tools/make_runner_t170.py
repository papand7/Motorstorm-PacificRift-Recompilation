def cpu_sampler(path, done):
    '''Cumulative CPU seconds per game thread every 5 s, system totals, and the other processes that used most CPU since the last sample.'''
    k = ctypes.WinDLL('kernel32', use_last_error=True)
    k.CreateToolhelp32Snapshot.restype = ctypes.c_void_p
    k.OpenProcess.restype = ctypes.c_void_p
    k.OpenThread.restype = ctypes.c_void_p
    for f in ('CloseHandle', 'GetThreadTimes', 'GetProcessTimes', 'Thread32First', 'Thread32Next', 'Process32FirstW', 'Process32NextW'):
        getattr(k, f).argtypes = None
    def times(fn, h):
        a, b, c, d = FT(), FT(), FT(), FT()
        ok = fn(ctypes.c_void_p(h), ctypes.byref(a), ctypes.byref(b), ctypes.byref(c), ctypes.byref(d))
        return (c.s() + d.s()) if ok else None
    prev = {}
    out = open(path, 'a', encoding='utf-8')
    while not done.wait(5.0):
        try:
            snap = k.CreateToolhelp32Snapshot(2 | 4, 0)
            pe = PROCESSENTRY32W(); pe.dwSize = ctypes.sizeof(pe)
            procs, game, ok = {}, [], k.Process32FirstW(ctypes.c_void_p(snap), ctypes.byref(pe))
            while ok:
                procs[pe.pid] = pe.name
                if pe.name.lower() == NAME.lower() + '.exe':
                    game.append(pe.pid)
                ok = k.Process32NextW(ctypes.c_void_p(snap), ctypes.byref(pe))
            te = THREADENTRY32(); te.dwSize = ctypes.sizeof(te)
            th, ok = {}, k.Thread32First(ctypes.c_void_p(snap), ctypes.byref(te))
            while ok:
                if te.th32OwnerProcessID in game:
                    h = k.OpenThread(0x0800, 0, te.th32ThreadID)
                    if h:
                        v = times(k.GetThreadTimes, h)
                        if v is not None:
                            th[te.th32ThreadID] = round(v, 2)
                        k.CloseHandle(ctypes.c_void_p(h))
                ok = k.Thread32Next(ctypes.c_void_p(snap), ctypes.byref(te))
            k.CloseHandle(ctypes.c_void_p(snap))
            others = []
            for pid, nm in procs.items():
                if pid in game or pid == os.getpid():
                    continue
                h = k.OpenProcess(0x1000, 0, pid)
                if not h:
                    continue
                v = times(k.GetProcessTimes, h)
                k.CloseHandle(ctypes.c_void_p(h))
                if v is None:
                    continue
                if pid in prev and v - prev[pid] > 0.25:
                    others.append([nm, pid, round(v - prev[pid], 2)])
                prev[pid] = v
            idle, kern, user = FT(), FT(), FT()
            k.GetSystemTimes(ctypes.byref(idle), ctypes.byref(kern), ctypes.byref(user))
            out.write(json.dumps({'t': round(time.time(), 2), 'game_pids': game, 'threads': th, 'sys_idle': round(idle.s(), 2), 'sys_busy': round(kern.s() + user.s() - idle.s(), 2),
                                  'others': sorted(others, key=lambda r: -r[2])[:8]}) + '\\n')
            out.flush()
        except Exception as e:
            out.write(json.dumps({'error': repr(e)}) + '\\n'); out.flush()


