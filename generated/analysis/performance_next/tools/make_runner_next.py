"""performance_next: in-game A/B runner for the texture-residency change (PROPOSED; needs authorisation to launch).
Derives performance_next/ab/run_next.py from t161/ab/run_t161.py: the same route, fast pacing, inputs, caps
(195 s game / 210 s host), race stop at entry + 150 s, fresh HDD copies per launch and the 12 CELLMARK frame dumps.
Arms, on one exe (key 'n' = build/motorstorm-perfnext-tex, from tools/build_next.cmd):
  E = T161 arm C environment (ENV_LEAN, PS3_LWCOND_WAKE unset): every new switch off -> must match T161 C
  T = E + RSX_TEX_SLOTS=1024 RSX_TEX_CACHE=1 RSX_TEX_WWATCH=1 RSX_TEX_BUDGET_MB=1024
  py -3 generated/analysis/performance_next/tools/make_runner_next.py
  py -3 generated/analysis/performance_next/ab/run_next.py prepare n ; launch E|T <tag>"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
AB = HERE.parent / 'ab'
T161 = HERE.parents[1] / 't161'
src = (T161 / 'ab' / 'run_t161.py').read_text(encoding='utf-8')


def sub(old, new, count=1):
    global src
    assert src.count(old) == count, (old[:80], src.count(old))
    src = src.replace(old, new)


sub('"""T161 fast race benchmark (generated by t161/tools/make_runner_t161.py from t158/ab/run_t158ab.py; PROPOSED, needs authorisation):\n',
    '"""performance_next texture-residency A/B (generated by performance_next/tools/make_runner_next.py from t161/ab/run_t161.py; '
    'PROPOSED, needs authorisation):\n  py -3 run_next.py prepare n ; launch E|T <tag>\n')
sub("sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'tools'))\n",
    "sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 't161' / 'tools'))   # nav_policy_t161\n")
i0, i1 = src.index("SRC_EXES = {"), src.index("EXE, EXE_SHA = None, None")
src = src[:i0] + "SRC_EXES = {'n': ROOT / 'build' / 'motorstorm-perfnext-tex' / 'MotorStormPacificRiftRecomp.exe'}\nHARD_KILL_S = 200.0   # as T161 (this slice replaces its line)\n" + src[i1:]
i0, i1 = src.index("ARMS = {"), src.index("RACE_STOP = {")
src = src[:i0] + """TEXRES = {'RSX_TEX_SLOTS': '1024', 'RSX_TEX_CACHE': '1', 'RSX_TEX_WWATCH': '1', 'RSX_TEX_BUDGET_MB': '1024'}
ARMS = {
    'E': ('n', ENV_LEAN),                 # every new switch off (T161 arm C environment)
    'T': ('n', {**ENV_LEAN, **TEXRES}),   # texture residency on
}
""" + src[i1:]
sub("RACE_STOP = {'C': 150.0, 'D': 150.0}", "RACE_STOP = {'E': 150.0, 'T': 150.0}")
i0 = src.index("NAV = {")
i1 = src.index("\n", src.index("'C': dict(settle_s=1.5, retries=2), 'D': dict(settle_s=1.5, retries=2)}")) + 1
src = src[:i0] + "NAV = {'E': dict(settle_s=1.5, retries=2), 'T': dict(settle_s=1.5, retries=2)}\n" + src[i1:]
sub("RUN_NAME = 't161-fast'", "RUN_NAME = 'perfnext'")
sub("            raise SystemExit('usage: run_t161.py launch N|F|H|L|A|B|C|D <tag>')",
    "            raise SystemExit('usage: run_next.py launch E|T <tag>')")
sub("        ARM, RUN_NAME = arm, f't161-fast-{arm}{tag}'", "        ARM, RUN_NAME = arm, f'perfnext-{arm}{tag}'")
AB.mkdir(exist_ok=True)
for name in ('cpath_sites.cfg', 'cpath_sites_v2.cfg', 'snapshot_manifest.json'):
    s = T161 / 'ab' / name
    if s.exists():
        (AB / name).write_bytes(s.read_bytes())
(AB / 'run_next.py').write_text(src, encoding='utf-8')
print('wrote', AB / 'run_next.py')
