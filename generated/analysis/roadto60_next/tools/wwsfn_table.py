"""roadto60_next: (image id, entry address) -> lifted function table for one Wws lift directory.

usage: py -3 wwsfn_table.py <lift dir> <out.c>
Reads wws_reloc_manifest.json (image ids, symbol prefixes) and scans each registered module's spu_recomp.c for
`void <prefix>spu_func_<ADDR>(spu_context* ctx) {`. Writes extern prototypes and a row table. Private output
(derived from the game's own module images)."""
import json
import re
import sys
from pathlib import Path

lift = Path(sys.argv[1])
out = Path(sys.argv[2])
man = json.loads((lift / "wws_reloc_manifest.json").read_text())
rx = re.compile(r"^void (\S+?)spu_func_([0-9A-Fa-f]{8})\(spu_context\* ctx\) \{", re.M)
rows = []
protos = []
for m in man:
    if not m.get("registered"):
        continue
    stem = m["file"][:-4]
    src = (lift / stem / "spu_recomp.c").read_text(encoding="utf-8", errors="replace")
    for mm in rx.finditer(src):
        fn = f"{mm.group(1)}spu_func_{mm.group(2).upper()}"
        if not fn.startswith(m["prefix"]):
            continue
        protos.append(fn)
        rows.append((m["image_id"], int(mm.group(2), 16), fn))
L = ["/* GENERATED by roadto60_next/tools/wwsfn_table.py (private: derived from the game's module images). */",
     '#include "spu_context.h"', "typedef struct { uint32_t image, addr; void (*fn)(spu_context*); } wwsfn_row;"]
L += [f"extern void {p}(spu_context*);" for p in protos]
L.append("const wwsfn_row wwsfn_rows[] = {")
L += [f"  {{ {img}u, 0x{addr:X}u, {fn} }}," for img, addr, fn in rows]
L.append("  { 0, 0, 0 }")
L.append("};")
L.append(f"const unsigned wwsfn_nrows = {len(rows)}u;")
out.write_text("\n".join(L) + "\n", encoding="utf-8")
print(f"{len(rows)} entries from {len({r[0] for r in rows})} images -> {out}")
