"""T167: in-game runner, derived from t162/ab/run_t162.py: same route, pacing, inputs, environment and fresh HDD copies per launch.
Caps 240 s game / 245 s host. One exe, build/motorstorm-t167 (ps3recomp 8a12a61). Arms, T162 arm A's environment plus diagnostics:
  A = RSX_GVF_ASYNC=0, fetch off (baseline)
  B = RSX_GVF_ASYNC=1, RSX_GPU_VERTEX_FETCH=1
RSX_PRESENT_INTERVAL is set in neither arm.
  py -3 generated/analysis/t167/tools/make_runner_t167.py
  py -3 generated/analysis/t167/ab/run_t167.py prepare g ; dryrun A|B ; launch A|B <tag>"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
AB = HERE.parent / 'ab'
T162 = HERE.parents[1] / 't162' / 'ab'
src = (T162 / 'run_t162.py').read_text(encoding='utf-8')
NL = chr(10)


def sub(old, new, count=1):
    global src
    assert src.count(old) == count, (old[:80], src.count(old))
    src = src.replace(old, new)


sub('"""T162 GPU vertex fetch D/A/B (generated by t162/tools/make_runner_t162.py from t161/ab/run_t161.py):' + NL + '  py -3 run_t162.py prepare g ; launch D|A|B <tag>' + NL,
    '"""T167 async fetch compile A/B (generated by t167/tools/make_runner_t167.py from t162/ab/run_t162.py):' + NL + '  py -3 run_t167.py prepare g ; dryrun A|B ; launch A|B <tag>' + NL)
sub("SRC_EXES = {'g': ROOT / 'build' / 'motorstorm-t162-gvf' / 'MotorStormPacificRiftRecomp.exe'}",
    "SRC_EXES = {'g': ROOT / 'build' / 'motorstorm-t167' / 'MotorStormPacificRiftRecomp.exe'}")
sub("HARD_KILL_S = 200.0   # as T161 (this slice replaces its line)", "HARD_KILL_S = 242.0   # after the 240 s game cap, inside the 245 s host cap")
i0, i1 = src.index("PROF = {'RSX_GPU_PROF'"), src.index("RACE_STOP = {")
src = src[:i0] + """PROF = {'RSX_GPU_PROF': '60', 'RSX_WAIT_DIAG': '1', 'RSX_SHADER_COMPILE_DIAG': '1'}
ARMS = {
    'A': ('g', {**ENV_LEAN, **PROF, 'RSX_GVF_ASYNC': '0'}),
    'B': ('g', {**ENV_LEAN, **PROF, 'RSX_GVF_ASYNC': '1', 'RSX_GPU_VERTEX_FETCH': '1'}),
}
""" + src[i1:]
sub("RACE_STOP = {'D': 150.0, 'A': 150.0, 'B': 150.0}", "RACE_STOP = {'A': 150.0, 'B': 150.0}")
sub("NAV = {k: dict(settle_s=1.5, retries=2) for k in 'DAB'}", "NAV = {k: dict(settle_s=1.5, retries=2) for k in 'AB'}")
sub("RUN_NAME = 't162'", "RUN_NAME = 't167'")
sub("'--timeout', '195']   # + fast_startup HARD_GRACE_S 15 = 210 s hard deadline", "'--timeout', '240']   # + HARD_GRACE_S 5 (set in main) = 245 s hard deadline")
sub("raise SystemExit('usage: run_t162.py launch D|A|B <tag>')", "raise SystemExit('usage: run_t167.py launch A|B <tag>')")
sub("ARM, RUN_NAME = arm, f't162-{arm}{tag}'", "ARM, RUN_NAME = arm, f't167-{arm}{tag}'")
sub("    fast_startup.MAX_TIMEOUT_S = 195.0" + NL, "    fast_startup.MAX_TIMEOUT_S = 240.0" + NL + "    fast_startup.HARD_GRACE_S = 5.0" + NL)
AB.mkdir(exist_ok=True)
for name in ('cpath_sites.cfg', 'cpath_sites_v2.cfg', 'snapshot_manifest.json'):
    s = T162 / name
    if s.exists():
        (AB / name).write_bytes(s.read_bytes())
(AB / 'run_t167.py').write_text(src, encoding='utf-8')
print('wrote', AB / 'run_t167.py')
