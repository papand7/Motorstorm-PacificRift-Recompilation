"""Transliterate one --chain-chunks group of a lifted SPU image into a native C function.

The native keeps the group's SPU registers in a local array (not ctx->gpr: LS stores and calls
through ctx could alias it), reaches LS through the same helpers, turns every SPU_CHAIN edge into
a plain goto (counting the steps the lifted code counts), and stores the registers back to ctx at
each exit (SPU_RET, stop). It is the group's statements, nothing else: the replay (spu_task_replay
verify) checks it against the recorded runs, registers and LS, bit for bit.

  python transl_native.py <spu_recomp.c> <group entry label: loc_00010890> <function name> <out.c>
         [--image-id N] [--entry-label loc_..]

Declines (returns 0, the lifted body runs) when chaining is not open, or when an LS diagnostic
is armed (the lifted gate would print what the rewrite skips)."""
import re
import sys
from pathlib import Path

src, entry_label, fname, out = sys.argv[1], sys.argv[2], sys.argv[3], Path(sys.argv[4])
image_id = int(sys.argv[sys.argv.index('--image-id') + 1]) if '--image-id' in sys.argv else 0
text = Path(src).read_text(encoding='utf-8').split('\n')

# the group that holds entry_label
lab_idx = next(i for i, l in enumerate(text) if l == entry_label + ':')
gstart = max(i for i in range(lab_idx) if text[i].startswith('static void ') and '_spu_grp_' in text[i])
gend = next(i for i in range(lab_idx, len(text)) if text[i] == '}')
body = text[lab_idx:gend]

RE_GPR = re.compile(r'ctx->gpr\[(\d+)\]')
RE_CHAIN = re.compile(r'SPU_CHAIN(?:_BACK)?\(ctx, (0x[0-9A-Fa-f]+)u, (loc_[0-9A-Fa-f]{8}), [A-Za-z0-9_]+\);')
out_lines = []
used = set()
for raw in body:
    t = raw.strip()
    if not t:
        continue
    if re.fullmatch(r'loc_[0-9A-Fa-f]{8}:', t):
        out_lines.append(t)
        continue
    t = RE_GPR.sub(lambda m: f'R[{m.group(1)}]', t)
    for m in RE_GPR.finditer(raw):
        used.add(int(m.group(1)))
    if 'SPU_RET(ctx);' in t:
        t = t.replace('SPU_RET(ctx);', 'SPU_RET_NAT();')
    elif t.startswith('ctx->stop_code'):
        # the stop: flush, the same statements, and the function is done
        t = ('STORE_ALL(); ctx->steps += nst; ctx->stop_code = 0x3FFFu; '
             'ctx->status = SPU_STATUS_STOPPED_BY_STOP; spu_stop(ctx); return 1;')
    t = RE_CHAIN.sub(lambda m: f'{{ ctx->pc = {m.group(1)}; ++nst; goto {m.group(2)}; }}', t)
    t = t.replace('/* nop */;', '')
    t = t.replace('/* branch hint (ignored) */;', '')
    if t:
        out_lines.append(t)

if not any('spu_stop(' in l for l in out_lines):
    raise SystemExit('no stop in the group: check the group')

prologue = ['    uint32_t nst = 0;', '    u128 R[128];', '    uint8_t* SPU_LS_RESTRICT ls = ctx->ls;']
prologue += [f'    R[{n}] = ctx->gpr[{n}];' for n in sorted(used)]
store = ' '.join(f'ctx->gpr[{n}] = R[{n}];' for n in sorted(used))

fn = [
    f'/* Generated by transl_native.py from the lifted group of {Path(src).parent.name}; private. */',
    f'static int {fname}(spu_context* ctx) {{',
    '    /* decline: the lifted code runs (chaining closed, or an LS diagnostic armed) */',
    '    if (!SPU_CHAIN_OK(ctx) || (g_spu_ls_diag != 0 && (g_spu_ls_diag > 0 || spu_ls_diag_resolve()))) return 0;',
    *prologue,
    f'#define STORE_ALL() do {{ {store} }} while (0)',
    '#define SPU_RET_NAT() do { STORE_ALL(); ctx->steps += nst; ctx->pc = R[0]._u32[0]; '
    'if (ctx->host_depth == 0) g_spu_trampoline_fn = spu_indirect_branch; return 1; } while (0)',
    *['    ' + l if not l.endswith(':') else l for l in out_lines],
    '#undef SPU_RET_NAT',
    '#undef STORE_ALL',
    '}',
]
hdr = [
    '/* Native rewrite of one lifted SPU group (spu_lifter.py SPU_NATIVE_FILE; PS3_SPU_NATIVE=0 turns it',
    ' * off). Registered for image %d at %s. Private: derived from the game\'s SPU code. */' % (image_id, entry_label),
    '#include "spu_context.h"',
    '#include "spu_helpers.h"',
    'extern int spu_native_register(int image_id, uint32_t addr, int (*fn)(spu_context*));',
    'extern void spu_stop(spu_context*);',
    'extern void spu_indirect_branch(spu_context* ctx);',
    '',
]
prefix = Path(src).parent.name + '_'
ctor = [
    '',
    '/* called from this image spu_recomp_register (spu_lifter.py SPU_NATIVE_FILE src=) */',
    'void %sspu_natives_register(void) {' % prefix,
    f'    spu_native_register({image_id}, 0x{int(entry_label[4:], 16):X}u, {fname});',
    '}',
    '',
]
out.write_text('\n'.join(hdr + fn + ctor), encoding='utf-8')
print(f'wrote {out}: {len(out_lines)} statements, {len(used)} registers')
