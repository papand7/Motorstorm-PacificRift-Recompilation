"""Lift one Havok image twice for the function-level harness (hvkdiff, the SPU interpreter as the
oracle): C0 = the lift with the native rewrites of SPU_NATIVE_FILE (its symbols prefixed c0_<short>_),
C1 = the same lift without them (c1_<short>_). Same layout as t158's hvk_lift_pair.py.

  python hvk_native_pair.py <ps3recomp tree> <gen dir> <out dir> <short> <native list file> [--chain-chunks]
The native list names the image as c0_<short> (the lifter's prefix without its trailing underscore).
"""
import json
import os
import subprocess
import sys
from pathlib import Path

TREE, GEN, OUT = (Path(a).resolve() for a in sys.argv[1:4])
SHORT, NATIVES = sys.argv[4], Path(sys.argv[5]).resolve()
EXTRA = sys.argv[6:]
sys.path.insert(0, str(TREE / 'tools'))
from find_spu_functions import detect_functions  # noqa: E402

src = GEN  # the image directory itself (code.bin, functions.json, image.elf)
blob = (src / 'image.elf').read_bytes()
_, (_off, base, _size) = detect_functions(blob, verbose=False)
image_id = int(os.environ.get('HVK_IMAGE_ID', '491898574'))
d = OUT / SHORT
for arm in ('c0', 'c1'):
    o = d / arm
    o.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ)
    if arm == 'c0':
        env['SPU_NATIVE_FILE'] = str(NATIVES)
    else:
        env.pop('SPU_NATIVE_FILE', None)
    cmd = [sys.executable, str(TREE / 'tools' / 'spu_lifter.py'), str(src / 'code.bin'), '--base', str(base),
           '--functions', str(src / 'functions.json'), '--symbol-prefix', f'{arm}_{SHORT}_',
           '--report', str(o / 'lift.json'), '--output', str(o), '--image-id', str(image_id), '--chain-chunks',
           '--fast-lower'] + EXTRA
    r = subprocess.run(cmd, capture_output=True, text=True, env=env)
    if r.returncode:
        sys.exit(f'{arm}: lifter failed\n{r.stdout}\n{r.stderr}')
    for fn in ('spu_recomp.c', 'spu_recomp.h'):
        p = o / fn
        t = p.read_text(encoding='utf-8')
        t = t.replace('#include "../../runtime/spu/spu_context.h"', '#include "spu_context.h"')
        t = t.replace('#include "../../runtime/spu/spu_helpers.h"', '#include "spu_helpers.h"')
        p.write_text(t, encoding='utf-8')
rep = json.loads((d / 'c0' / 'lift.json').read_text())
starts = sorted({s for s, _ in rep['functions']})
calls = sorted(set(rep['call_targets']))
lo, hi = min(s for s, _ in rep['functions']), max(e for _, e in rep['functions'])
L = ['/* generated by hvk_native_pair.py */', '#include "spu_context.h"', '#include "hvk_table.h"']
for arm in ('c0', 'c1'):
    L.append(f'extern void {arm}_{SHORT}_spu_recomp_register(void);')
    for a in calls:
        L.append(f'extern void {arm}_{SHORT}_spu_func_{a:08X}(spu_context*);')
L.append(f'static const uint32_t s_starts[] = {{{", ".join(hex(a) for a in starts)}}};')
L.append('static const hvk_entry s_calls[] = {')
for a in calls:
    L.append(f'    {{0x{a:X}u, c0_{SHORT}_spu_func_{a:08X}, c1_{SHORT}_spu_func_{a:08X}}},')
L.append('};')
L.append(f'const hvk_image hvk_img = {{"{SHORT}", "{(src / "image.elf").as_posix()}", {image_id}, '
         f'0x{lo:X}u, 0x{hi:X}u, s_starts, {len(starts)}u, s_calls, {len(calls)}u, '
         f'c0_{SHORT}_spu_recomp_register, c1_{SHORT}_spu_recomp_register}};')
(d / 'table.c').write_text('\n'.join(L) + '\n', encoding='utf-8')
print(SHORT, 'functions', len(starts), 'call targets', len(calls))
