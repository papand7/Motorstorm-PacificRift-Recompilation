"""spunat2: two copies of an existing lift for the fnx harness, plus its image table.

  python mkpair.py <spec.json> <out dir> [--native <file.c>] [--no-hooks]

c0_<short>_ = the lift with a native hook at the head of every function in spec["hooks"] (the hook
returns from the lifted function when the native accepted: the native did the exit itself), the native
source included at its end and registered from its spu_recomp_register; c1_<short>_ = the unchanged
lift (the baseline). The existing lift is only copied and renamed, never re-lifted, so the baseline is
exactly the production lift. Output is private (game-derived)."""
import json
import re
import sys
from pathlib import Path

spec_path, out = Path(sys.argv[1]), Path(sys.argv[2])
args = sys.argv[3:]
spec = json.loads(spec_path.read_text())
native = None
if '--native' in args:
    native = Path(args[args.index('--native') + 1]).resolve()
elif spec.get('native'):
    native = (spec_path.parent / spec['native']).resolve()
hooks = [] if '--no-hooks' in args else [int(h, 0) for h in spec.get('hooks', [])]
c0lift = Path(args[args.index('--c0-lift') + 1]) if '--c0-lift' in args else None   # a lift with the lifter's own hooks
short, prefix = spec['short'], spec['prefix']
lift = Path(spec['lift'])
src = (lift / 'spu_recomp.c').read_text(encoding='utf-8')
hdr = (lift / 'spu_recomp.h').read_text(encoding='utf-8')
out.mkdir(parents=True, exist_ok=True)


def fix_includes(t):
    return re.sub(r'#include "(?:\.\./)+runtime/spu/(spu_[a-z_]+\.h)"', r'#include "\1"', t)


def add_hooks(t, pfx):
    for h in hooks:
        head = f'void {pfx}spu_func_{h:08X}(spu_context* ctx) {{\n'
        assert t.count(head) == 1, f'no function 0x{h:X}'
        t = t.replace(head, head + f'    if (spu_native_entry(ctx, 0x{h:X}u)) return;   /* spunat2 native hook */\n')
    reg = f'void {pfx}spu_recomp_register(void) {{\n'
    assert t.count(reg) == 1
    t = t.replace(reg, f'#define LIFT(x) {pfx}##x\n#include "{native.as_posix()}"\n#undef LIFT\n' + reg +
                  '    nat_register_all();\n')
    t = t.replace('#include "spu_recomp.h"\n',
                  '#include "spu_recomp.h"\nint spu_native_entry(spu_context* ctx, uint32_t addr);\n', 1)
    return t


for arm in ('c0', 'c1'):
    d = out / arm
    d.mkdir(exist_ok=True)
    p = f'{arm}_{short}_'
    t = fix_includes(src).replace(prefix, p)
    if arm == 'c0' and c0lift:
        t = fix_includes((c0lift / 'spu_recomp.c').read_text(encoding='utf-8')).replace(prefix, p)
        m = re.search(r'#include "([^"]+)"   /\* SPU_NATIVE_FILE src= \*/', t)
        if m:
            w = Path(m.group(1)).read_text(encoding='utf-8').replace(prefix, p)
            (d / 'natives_wrapper.c').write_text(w, encoding='utf-8')
            t = t.replace(m.group(0), f'#include "{(d / "natives_wrapper.c").resolve().as_posix()}"')
    elif arm == 'c0' and hooks:
        t = add_hooks(t, p)
    (d / 'spu_recomp.c').write_text(t, encoding='utf-8')
    h = (c0lift / 'spu_recomp.h').read_text(encoding='utf-8') if (arm == 'c0' and c0lift) else hdr
    (d / 'spu_recomp.h').write_text(fix_includes(h).replace(prefix, p), encoding='utf-8')

starts = sorted({int(a, 16) for a in re.findall(r'\{ 0x([0-9A-Fa-f]{8})u, ' + re.escape(prefix), src)})
ents = spec['entries']
L = ['/* generated by spunat2 mkpair.py */', '#include "spu_context.h"', '#include "fnx.h"']
for arm in ('c0', 'c1'):
    L.append(f'extern void {arm}_{short}_spu_recomp_register(void);')
    for a in ents:
        L.append(f'extern void {arm}_{short}_spu_func_{int(a, 0):08X}(spu_context*);')
L.append(f'static const uint32_t s_starts[] = {{{", ".join(hex(a) for a in starts)}}};')
L.append('static const fx_entry s_ents[] = {')
for a, shape in ents.items():
    a = int(a, 0)
    L.append(f'    {{0x{a:X}u, c0_{short}_spu_func_{a:08X}, c1_{short}_spu_func_{a:08X}, {json.dumps(shape)}}},')
L.append('};')
code_lo = spec.get('code_lo', min(starts))
code_hi = spec['code_hi']
L.append(f'const fx_image fx_img = {{"{short}", "{Path(spec["image"]).as_posix()}", {int(spec["raw"])}, '
         f'0x{spec.get("link_base", 0):X}u, {spec["image_id"]}, 0x{code_lo:X}u, 0x{code_hi:X}u, s_starts, '
         f'{len(starts)}u, s_ents, {len(ents)}u, c0_{short}_spu_recomp_register, c1_{short}_spu_recomp_register, '
         f'0x{spec.get("work_lo", 0):X}u}};')
(out / 'table.c').write_text('\n'.join(L) + '\n', encoding='utf-8')
print(short, 'starts', len(starts), 'entries', len(ents), 'hooks', len(hooks), 'native', native)
