"""T156 Havok worker-pool game A/B runner (PROPOSED; needs authorisation before any launch).
Derives t156/ab/run_t156ab.py from t154/ab/run_t154ab.py: same route, intro skip, controller, race entry,
stop at race entry + 90 s, T154 arm BA environment (T153 COMMON + PERF + T150 + Wws stats + Wws AOT).
Changes:
- exe w = build/motorstorm-t156 (agent/t156-havok-worker-optimization + port-t156, MSPR_WWS_AOT=ON);
- the critical-path window moves into the light scene: host s 150..172 (T154 BA race entry 145.5-147.6 s,
  light phase to about 170 s; T154's 175..240 window missed it);
- arms:  S = T154 BA (pool off)   P = S + PS3_SPU_TASK_POOL=1 (the one switch under test)
         D = S + PS3_SPU_TASK_STATS=1000 (diagnostic, one run, not timed: splits task time into MFC/atomic).
  py -3 generated/analysis/t156/tools/make_runner_t156.py
  py -3 generated/analysis/t156/ab/run_t156ab.py prepare w | launch S|P|D <tag>"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
AB = HERE.parent / 'ab'
src = (HERE.parents[1] / 't154' / 'ab' / 'run_t154ab.py').read_text(encoding='utf-8')


def sub(old, new, count=1):
    global src
    assert src.count(old) == count, (old[:80], src.count(old))
    src = src.replace(old, new)


sub('"""T154 Wws AOT A/B (generated by t154/tools/make_runner_t154.py from t153/ab/run_t153ab.py; authorised: 4 launches):\n',
    '"""T156 Havok worker-pool A/B (generated by t156/tools/make_runner_t156.py from t154/ab/run_t154ab.py; PROPOSED, needs authorisation):\n')
sub("  py -3 run_t154ab.py launch B|BA <tag>\n", "  py -3 run_t156ab.py launch S|P|D <tag>\n")
sub("SRC_EXES = {'w': ROOT / 'build' / 'motorstorm-t154' / 'MotorStormPacificRiftRecomp.exe'}",
    "SRC_EXES = {'w': ROOT / 'build' / 'motorstorm-t156' / 'MotorStormPacificRiftRecomp.exe'}")
sub("TRACE = {'PS3_CRITICAL_PATH_TRACE': '175:65:{rt}/cpath.txt'}   # host s 175..240; T149 race entry 149-154 s",
    "TRACE = {'PS3_CRITICAL_PATH_TRACE': '150:22:{rt}/cpath.txt'}   # host s 150..172: the light scene (T154 BA entry 145.5-147.6 s)")
i0, i1 = src.index("ARMS = {"), src.index("RSXI_AT_S = 30.0")
src = src[:i0] + """POOL = {'PS3_SPU_TASK_POOL': '1'}                    # T156: the one switch under test
TSTAT = {'PS3_SPU_TASK_STATS': '1000'}                # T156 diagnostic counters (arm D only)
ARMS = {
    'S': ('w', {**COMMON, **PERF, **TRACE, **T150, **WSTAT, **AOT}),            # = T154 arm BA
    'P': ('w', {**COMMON, **PERF, **TRACE, **T150, **WSTAT, **AOT, **POOL}),
    'D': ('w', {**COMMON, **PERF, **TRACE, **T150, **WSTAT, **AOT, **TSTAT}),
}
""" + src[i1:]
sub("RUN_NAME = 't154-ab'", "RUN_NAME = 't156-ab'")
sub("            raise SystemExit('usage: run_t154ab.py launch B|BA <tag>')",
    "            raise SystemExit('usage: run_t156ab.py launch S|P|D <tag>')")
sub("        ARM, RUN_NAME = arm, f't154-ab-{tag}'", "        ARM, RUN_NAME = arm, f't156-ab-{tag}'")
AB.mkdir(exist_ok=True)
for name in ('cpath_sites.cfg', 'snapshot_manifest.json'):
    s = HERE.parents[1] / 't154' / 'ab' / name
    if s.exists():
        (AB / name).write_bytes(s.read_bytes())
(AB / 'run_t156ab.py').write_text(src, encoding='utf-8')
print('wrote', AB / 'run_t156ab.py')
