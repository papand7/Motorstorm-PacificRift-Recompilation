"""T153 unified game A/B (PROPOSED, needs explicit authorisation; T150/T151 authorisations do not cover it).
Derives t153/ab/run_t153ab.py from t149/ab/run_t149ab.py: same route, intro skip, controller; race entry = first
[rsx-hb] with last_draws >= 200; stop at race entry + 90 s; hard cap 440 s.
- two exes, copied and sha-pinned by `prepare a` / `prepare i`:
    a  build/motorstorm-t153-base  (ps3recomp 80fe5de = T146 unmodified, port/)
    i  build/motorstorm-t153       (integration/t153-continuous-performance + port-t153)
- every arm: the T146 defaults explicitly (COMMON), PS3_TEX_SNAPSHOT_STATS=1000, the T149 diagnostics and the
  critical-path trace (host s 175..240; the analysis flags a race entry after 165 s);
- arms (PERF = the T122/T149 performance preset: epoch, compact, shader cache, SRV reuse, bind dedup, event sched):
    A  exe a, T146 defaults
    P  exe a, + PERF                                  (T149 P1 reference)
    Z  exe i, T146 defaults, every T150/T151 switch off  (integration exe off == baseline)
    B  exe i, + PERF + PS3_TEX_SNAPSHOT_WWATCH=1      (T150; epoch is already in PERF)
    C  exe i, + PERF + RSX_VP_FAST_FETCH=1 + PS3_FRAME_CLOCK_KICK=1   (T151)
    D  exe i, + PERF + T150 + T151
    E  D + T152: PS3_ICALL_FAST=1 (aca2ebd; refused if T152 is emptied)
- no RSXI, no debug layer, no physics/pacing switch.
  py -3 generated/analysis/t153/tools/make_runner_t153.py"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
AB = HERE.parent / 'ab'
src = (HERE.parents[1] / 't149' / 'ab' / 'run_t149ab.py').read_text(encoding='utf-8')


def sub(old, new, count=1):
    global src
    assert src.count(old) == count, (old[:80], src.count(old))
    src = src.replace(old, new)


sub('"""T149 bounded A/B (generated by t149/ab/make_runner.py from t145/ab/run_t145ab.py; PROPOSED, needs authorisation):\n',
    '"""T153 unified A/B (generated by t153/tools/make_runner_t153.py from t149/ab/run_t149ab.py; PROPOSED, needs authorisation):\n')
sub("  py -3 run_t149ab.py launch P0|P1|P2|P3 <tag>\n", "  py -3 run_t153ab.py launch A|P|Z|B|C|D|E <tag>\n")
sub("SRC_EXES = {'b': ROOT / 'build' / 'motorstorm-t149' / 'MotorStormPacificRiftRecomp.exe'}",
    "SRC_EXES = {'a': ROOT / 'build' / 'motorstorm-t153-base' / 'MotorStormPacificRiftRecomp.exe',\n"
    "            'i': ROOT / 'build' / 'motorstorm-t153' / 'MotorStormPacificRiftRecomp.exe'}")
i0, i1 = src.index("TRACE = {"), src.index("RSXI_AT_S = 30.0")
src = src[:i0] + """COMMON['PS3_TEX_SNAPSHOT_STATS'] = '1000'
TRACE = {'PS3_CRITICAL_PATH_TRACE': '175:65:{rt}/cpath.txt'}   # host s 175..240; T149 race entry 149-154 s
T150 = {'PS3_TEX_SNAPSHOT_WWATCH': '1'}
T151 = {'RSX_VP_FAST_FETCH': '1', 'PS3_FRAME_CLOCK_KICK': '1'}
T152 = {'PS3_ICALL_FAST': '1'}   # T152 aca2ebd (t153 2a764e1); E must log '[icall-fast] PS3_ICALL_FAST=1: indirect calls use'
ARMS = {
    'A': ('a', {**COMMON, **TRACE}),
    'P': ('a', {**COMMON, **PERF, **TRACE}),
    'Z': ('i', {**COMMON, **TRACE}),
    'B': ('i', {**COMMON, **PERF, **TRACE, **T150}),
    'C': ('i', {**COMMON, **PERF, **TRACE, **T151}),
    'D': ('i', {**COMMON, **PERF, **TRACE, **T150, **T151}),
    'E': ('i', {**COMMON, **PERF, **TRACE, **T150, **T151, **T152}),
}
""" + src[i1:]
sub("RUN_NAME = 't149-ab'", "RUN_NAME = 't153-ab'")
sub("        if arm not in ARMS or not tag:\n            raise SystemExit('usage: run_t149ab.py launch P0|P1|P2|P3 <tag>')",
    "        if arm not in ARMS or not tag:\n            raise SystemExit('usage: run_t153ab.py launch A|P|Z|B|C|D|E <tag>')\n"
    "        if arm == 'E' and not T152:\n            raise SystemExit('arm E: no T152 switches integrated yet')")
sub("        ARM, RUN_NAME = arm, f't149-ab-{tag}'", "        ARM, RUN_NAME = arm, f't153-ab-{tag}'")
AB.mkdir(exist_ok=True)
(AB / 'run_t153ab.py').write_text(src, encoding='utf-8')
print('wrote', AB / 'run_t153ab.py')
