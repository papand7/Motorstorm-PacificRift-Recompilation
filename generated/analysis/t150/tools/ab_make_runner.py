"""T150 bounded game A/B (PROPOSED, needs authorisation): derive run_t150ab.py from t149/ab/run_t149ab.py
(same route, intro skip, controller; race entry = first [rsx-hb] with last_draws >= 200; stop at race entry + 90 s;
hard cap 440 s).
- one exe: build/motorstorm-t150 (ps3recomp-t150-rsx-performance + port-t150), copied and sha-pinned by `prepare b`;
- every arm: the T146 integrated defaults explicitly, PS3_TEX_SNAPSHOT_STATS=1000, the T149 diagnostics and the
  T149 critical-path trace (host s 175..240; the analysis flags a race entry after 165 s);
- arms (T146 baseline = snapshot hashing on every capture):
    A  T146 baseline
    B  A + PS3_TEX_SNAPSHOT_EPOCH=1   (T122)
    C  A + PS3_TEX_SNAPSHOT_WWATCH=1  (T150; also makes the port's reservation write-watched)
    D  A + both
- no RSXI, no debug layer, no physics/pacing switch."""
from pathlib import Path

HERE = Path(__file__).resolve().parent
src = (HERE.parents[1] / 't149' / 'ab' / 'run_t149ab.py').read_text(encoding='utf-8')


def sub(old, new, count=1):
    global src
    assert src.count(old) == count, (old[:80], src.count(old))
    src = src.replace(old, new)


sub('"""T149 bounded A/B (generated by t149/ab/make_runner.py from t145/ab/run_t145ab.py; PROPOSED, needs authorisation):\n',
    '"""T150 bounded A/B (generated by t150/ab/make_runner.py from t149/ab/run_t149ab.py; PROPOSED, needs authorisation):\n')
sub("  py -3 run_t149ab.py launch P0|P1|P2|P3 <tag>\n", "  py -3 run_t150ab.py launch A|B|C|D <tag>\n")
sub("SRC_EXES = {'b': ROOT / 'build' / 'motorstorm-t149' / 'MotorStormPacificRiftRecomp.exe'}",
    "SRC_EXES = {'b': ROOT / 'build' / 'motorstorm-t150' / 'MotorStormPacificRiftRecomp.exe'}")
i0, i1 = src.index("PERF = {"), src.index("RSXI_AT_S = 30.0")
src = src[:i0] + """COMMON['PS3_TEX_SNAPSHOT_STATS'] = '1000'
TRACE = {'PS3_CRITICAL_PATH_TRACE': '175:65:{rt}/cpath.txt'}   # host s 175..240; T149 race entry 149-154 s
EPOCH, WWATCH = {'PS3_TEX_SNAPSHOT_EPOCH': '1'}, {'PS3_TEX_SNAPSHOT_WWATCH': '1'}
ARMS = {
    'A': ('b', {**COMMON, **TRACE}),
    'B': ('b', {**COMMON, **TRACE, **EPOCH}),
    'C': ('b', {**COMMON, **TRACE, **WWATCH}),
    'D': ('b', {**COMMON, **TRACE, **EPOCH, **WWATCH}),
}
""" + src[i1:]
sub("RUN_NAME = 't149-ab'", "RUN_NAME = 't150-ab'")
sub("            raise SystemExit('usage: run_t149ab.py launch P0|P1|P2|P3 <tag>')",
    "            raise SystemExit('usage: run_t150ab.py launch A|B|C|D <tag>')")
sub("        ARM, RUN_NAME = arm, f't149-ab-{tag}'", "        ARM, RUN_NAME = arm, f't150-ab-{tag}'")
(HERE / 'run_t150ab.py').write_text(src, encoding='utf-8')
print('wrote run_t150ab.py')
