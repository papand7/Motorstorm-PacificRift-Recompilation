"""T154 Wws AOT game A/B (authorised in the T154 brief: B, BA, B, BA; 4 launches, no others).
Derives t154/ab/run_t154ab.py from t153/ab/run_t153ab.py: same route, intro skip, controller, race entry,
stop at race entry + 90 s, T153 COMMON + PERF + TRACE + T150 (= T153 arm B). Changes:
- one exe for both arms, `prepare w` copies and sha-pins it:
    w  build/motorstorm-t154  (agent/t154-wws-aot-critical-path + port-t154, MSPR_WWS_AOT=ON)
- both arms add PS3_SPU_WWS_STATS=1000:3214:1320 (per-module Wws job counters, read-only);
- arm BA adds the only difference, PS3_SPU_WWS_AOT=1.
  py -3 generated/analysis/t154/tools/make_runner_t154.py"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
AB = HERE.parent / 'ab'
src = (HERE.parents[1] / 't153' / 'ab' / 'run_t153ab.py').read_text(encoding='utf-8')


def sub(old, new, count=1):
    global src
    assert src.count(old) == count, (old[:80], src.count(old))
    src = src.replace(old, new)


sub('"""T153 unified A/B (generated by t153/tools/make_runner_t153.py from t149/ab/run_t149ab.py; PROPOSED, needs authorisation):\n',
    '"""T154 Wws AOT A/B (generated by t154/tools/make_runner_t154.py from t153/ab/run_t153ab.py; authorised: 4 launches):\n')
sub("  py -3 run_t153ab.py launch A|P|Z|B|C|D|E <tag>\n", "  py -3 run_t154ab.py launch B|BA <tag>\n")
sub("SRC_EXES = {'a': ROOT / 'build' / 'motorstorm-t153-base' / 'MotorStormPacificRiftRecomp.exe',\n"
    "            'i': ROOT / 'build' / 'motorstorm-t153' / 'MotorStormPacificRiftRecomp.exe'}",
    "SRC_EXES = {'w': ROOT / 'build' / 'motorstorm-t154' / 'MotorStormPacificRiftRecomp.exe'}")
i0, i1 = src.index("ARMS = {"), src.index("RSXI_AT_S = 30.0")
src = src[:i0] + """WSTAT = {'PS3_SPU_WWS_STATS': '1000:3214:1320'}   # T154 per-module Wws job counters, both arms
AOT = {'PS3_SPU_WWS_AOT': '1'}                        # T152 9cd7ef2 / T106: the one switch under test
ARMS = {
    'B': ('w', {**COMMON, **PERF, **TRACE, **T150, **WSTAT}),          # = T153 arm B, AOT exe, AOT off
    'BA': ('w', {**COMMON, **PERF, **TRACE, **T150, **WSTAT, **AOT}),
}
""" + src[i1:]
sub("RUN_NAME = 't153-ab'", "RUN_NAME = 't154-ab'")
sub("        if arm not in ARMS or not tag:\n            raise SystemExit('usage: run_t153ab.py launch A|P|Z|B|C|D|E <tag>')\n"
    "        if arm == 'E' and not T152:\n            raise SystemExit('arm E: no T152 switches integrated yet')",
    "        if arm not in ARMS or not tag:\n            raise SystemExit('usage: run_t154ab.py launch B|BA <tag>')")
sub("        ARM, RUN_NAME = arm, f't153-ab-{tag}'", "        ARM, RUN_NAME = arm, f't154-ab-{tag}'")
sub("        # T68 diagnostics (existing, env only; no TEX_SAVE, no DEPTH_OFF, WWS AOT not set)\n",
    "        # T68 diagnostics (existing, env only; no TEX_SAVE, no DEPTH_OFF; WWS AOT only in arm BA)\n")
AB.mkdir(exist_ok=True)
(AB / 'run_t154ab.py').write_text(src, encoding='utf-8')
print('wrote', AB / 'run_t154ab.py')
