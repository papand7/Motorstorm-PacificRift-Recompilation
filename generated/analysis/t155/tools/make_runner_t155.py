"""T155 diagnostic launch (authorised in the T155 brief: one launch, no retry).
Derives t155/ab/run_t155diag.py from t154/ab/run_t154ab.py: same route, controller, race entry, stop at race
entry + 90 s, and exactly T154 arm BA's environment (T153 preset + T150 write-watch + PS3_SPU_WWS_STATS +
PS3_SPU_WWS_AOT=1), plus RSX_TEXREC_STATS=1 (per-pass texture-recording counters, read-only).
- exe `prepare d`: build/motorstorm-t155 (agent/t155-rsx-heavy-texture + port-t155, MSPR_WWS_AOT=ON).
  py -3 generated/analysis/t155/tools/make_runner_t155.py"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
AB = HERE.parent / 'ab'
src = (HERE.parents[1] / 't154' / 'ab' / 'run_t154ab.py').read_text(encoding='utf-8')


def sub(old, new, count=1):
    global src
    assert src.count(old) == count, (old[:80], src.count(old))
    src = src.replace(old, new)


sub('"""T154 Wws AOT A/B (generated by t154/tools/make_runner_t154.py from t153/ab/run_t153ab.py; authorised: 4 launches):\n',
    '"""T155 diagnostic launch (generated by t155/tools/make_runner_t155.py from t154/ab/run_t154ab.py; authorised: 1 launch):\n')
sub("  py -3 run_t154ab.py launch B|BA <tag>\n", "  py -3 run_t155diag.py launch D <tag>\n")
sub("SRC_EXES = {'w': ROOT / 'build' / 'motorstorm-t154' / 'MotorStormPacificRiftRecomp.exe'}",
    "SRC_EXES = {'d': ROOT / 'build' / 'motorstorm-t155' / 'MotorStormPacificRiftRecomp.exe'}")
sub("""ARMS = {
    'B': ('w', {**COMMON, **PERF, **TRACE, **T150, **WSTAT}),          # = T153 arm B, AOT exe, AOT off
    'BA': ('w', {**COMMON, **PERF, **TRACE, **T150, **WSTAT, **AOT}),
}""", """TEXREC = {'RSX_TEXREC_STATS': '1'}   # T155 per-pass [tex-rec] lines
ARMS = {
    'D': ('d', {**COMMON, **PERF, **TRACE, **T150, **WSTAT, **AOT, **TEXREC}),   # = T154 arm BA + TEXREC
}""")
sub("RUN_NAME = 't154-ab'", "RUN_NAME = 't155-diag'")
sub("            raise SystemExit('usage: run_t154ab.py launch B|BA <tag>')",
    "            raise SystemExit('usage: run_t155diag.py launch D <tag>')\n"
    "        if list(HERE.glob('runtime-*')):\n"
    "            raise SystemExit('T155 authorises one diagnostic launch; a runtime dir already exists')")
sub("        ARM, RUN_NAME = arm, f't154-ab-{tag}'", "        ARM, RUN_NAME = arm, f't155-diag-{tag}'")
AB.mkdir(exist_ok=True)
(AB / 'run_t155diag.py').write_text(src, encoding='utf-8')
print('wrote', AB / 'run_t155diag.py')
