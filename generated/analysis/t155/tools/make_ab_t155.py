"""T155 game A/B (PROPOSED: needs explicit authorisation for 4 launches A, B, A, B; nothing here launches).
Derives t155/ab/run_t155ab.py from t154/ab/run_t154ab.py: same route, controller, race entry, stop at race entry
+ 90 s. Both arms: one exe (`prepare f`: build/motorstorm-t155 at f514913, MSPR_WWS_AOT=ON), T154 arm BA's
environment (T153 preset + T150 write-watch + PS3_SPU_WWS_STATS + PS3_SPU_WWS_AOT=1) + RSX_TEXREC_STATS=1.
    A  RSX_TEX_SLOTS unset (96 slots: the T154 behaviour)
    B  RSX_TEX_SLOTS=1024
Analysis: t154/tools/phase_match_t154.py + phase_sites_t154.py (race-frame indices), t155/tools/ana_texrec_t155.py.
  py -3 generated/analysis/t155/tools/make_ab_t155.py"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
AB = HERE.parent / 'ab'
src = (HERE.parents[1] / 't154' / 'ab' / 'run_t154ab.py').read_text(encoding='utf-8')


def sub(old, new, count=1):
    global src
    assert src.count(old) == count, (old[:80], src.count(old))
    src = src.replace(old, new)


sub('"""T154 Wws AOT A/B (generated by t154/tools/make_runner_t154.py from t153/ab/run_t153ab.py; authorised: 4 launches):\n',
    '"""T155 RSX_TEX_SLOTS A/B (generated by t155/tools/make_ab_t155.py from t154/ab/run_t154ab.py; PROPOSED, needs authorisation):\n')
sub("  py -3 run_t154ab.py launch B|BA <tag>\n", "  py -3 run_t155ab.py launch A|B <tag>\n")
sub("SRC_EXES = {'w': ROOT / 'build' / 'motorstorm-t154' / 'MotorStormPacificRiftRecomp.exe'}",
    "SRC_EXES = {'f': ROOT / 'build' / 'motorstorm-t155' / 'MotorStormPacificRiftRecomp.exe'}")
sub("""ARMS = {
    'B': ('w', {**COMMON, **PERF, **TRACE, **T150, **WSTAT}),          # = T153 arm B, AOT exe, AOT off
    'BA': ('w', {**COMMON, **PERF, **TRACE, **T150, **WSTAT, **AOT}),
}""", """TEXREC = {'RSX_TEXREC_STATS': '1'}
SLOTS = {'RSX_TEX_SLOTS': '1024'}   # T155 f514913: the one switch under test
ARMS = {
    'A': ('f', {**COMMON, **PERF, **TRACE, **T150, **WSTAT, **AOT, **TEXREC}),            # = T154 arm BA
    'B': ('f', {**COMMON, **PERF, **TRACE, **T150, **WSTAT, **AOT, **TEXREC, **SLOTS}),
}""")
sub("RUN_NAME = 't154-ab'", "RUN_NAME = 't155-ab'")
sub("            raise SystemExit('usage: run_t154ab.py launch B|BA <tag>')",
    "            raise SystemExit('usage: run_t155ab.py launch A|B <tag>')")
sub("        ARM, RUN_NAME = arm, f't154-ab-{tag}'", "        ARM, RUN_NAME = arm, f't155-ab-{tag}'")
AB.mkdir(exist_ok=True)
(AB / 'run_t155ab.py').write_text(src, encoding='utf-8')
(AB / 'seq_t155ab.sh').write_text("""#!/bin/bash
# T155 A/B (NOT AUTHORISED YET): 4 launches, sequential A, B, A, B. No builds or tests alongside.
cd "$(dirname "$0")"
for t in Ar1 Br1 Ar2 Br2; do
  a=${t%r*}
  echo "$t start $(date +%H:%M:%S)" >> seq_t155ab.log
  py -3 run_t155ab.py launch $a $t > launch_$t.txt 2>&1
  echo "$t done: rc=$? $(tail -1 launch_$t.txt) $(date +%H:%M:%S)" >> seq_t155ab.log
done
echo ALL_DONE >> seq_t155ab.log
""", encoding='utf-8')
print('wrote', AB / 'run_t155ab.py', AB / 'seq_t155ab.sh')
